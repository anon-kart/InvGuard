"""
contract_normalizer.py
======================
Preprocesses target contract source to resolve common Foundry compilation
issues without changing contract semantics.

Handled issues:
  - ``internal constant`` on library functions (pre-0.4.16 syntax) → ``internal pure``
  - Missing SPDX license identifier → adds MIT
  - ``throw`` statements (deprecated in 0.4.x) → ``revert()``
  - ``var`` declarations → explicit types (limited heuristic)
  - ``function ContractName()`` old-style constructors → ``constructor()``
"""

import re
from typing import Optional


def normalize_for_foundry(src: str) -> str:
    """Apply all normalizations in sequence.  Returns the (possibly
    modified) source."""
    if not src:
        return src

    s = src
    s = _fix_constant_to_pure(s)
    s = _add_spdx_if_missing(s)
    return s


def _fix_constant_to_pure(src: str) -> str:
    """Replace ``internal constant`` with ``internal pure`` in library
    functions.  The ``constant`` modifier on functions was valid in
    Solidity <0.4.17 but is rejected by 0.5+.  Since these are library
    functions that only do pure arithmetic, ``pure`` is the correct
    replacement.

    We apply the replacement globally to all ``internal constant``
    occurrences rather than trying to scope it to library blocks,
    because nested braces make library-block regex fragile and the
    replacement is safe everywhere (no legitimate ``internal constant``
    exists in modern Solidity)."""
    return re.sub(
        r'\binternal\s+constant\b',
        'internal pure',
        src,
    )


def _add_spdx_if_missing(src: str) -> str:
    """Add SPDX license identifier if not present.  Foundry warns (and
    some strict configs error) without it."""
    if "SPDX-License-Identifier" in src:
        return src
    return "// SPDX-License-Identifier: MIT\n" + src


def normalize_bectoken(src: str) -> str:
    """BECToken-specific normalization.

    The BECToken contract uses ``internal constant`` on SafeMath library
    functions and ``public constant`` on ERC20 view functions.  Both are
    pre-0.4.17 syntax.

    NOTE: We deliberately do NOT convert old-style constructors
    (``function ContractName()``) to ``constructor()``.  The Target
    alias generated by exploit_executor calls the parent constructor
    by name (``contract Target is BecToken { constructor() payable
    BecToken() {} }``).  Converting the named constructor breaks this
    parent call.  Solc 0.4.22+ accepts both syntaxes, so the old-style
    constructor compiles fine.
    """
    s = src
    # Fix library functions: internal constant -> internal pure
    s = _fix_constant_to_pure(s)
    # Fix FUNCTION declarations: public constant -> public view
    # ONLY when it appears in a function signature (followed by 'returns'
    # or '{'). Do NOT touch state variable declarations like
    # 'string public constant name = ...' where 'constant' is valid.
    s = re.sub(
        r'\bfunction\s+(\w+)\s*\(([^)]*)\)\s*public\s+constant\b',
        r'function \1(\2) public view',
        s,
    )
    # Do NOT convert old-style constructors — they break Target alias
    return _add_spdx_if_missing(s)


def extract_helper_contracts(src: str, main_contract: str) -> list:
    """Extract names and source of helper contracts defined in the same
    file as the main contract.  Returns [(name, source), ...]."""
    helpers = []
    # Find all contract blocks
    for m in re.finditer(r'(contract\s+(\w+)\s*(?:is\s+[^{]*)?\{)', src):
        name = m.group(2)
        if name == main_contract:
            continue
        start = m.start()
        # Find matching closing brace
        depth = 0
        i = m.end() - 1  # start from the opening brace
        while i < len(src):
            if src[i] == '{':
                depth += 1
            elif src[i] == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        body = src[start:i + 1]
        helpers.append((name, body))
    return helpers


def extract_required_interface(contract_src: str, type_name: str) -> Optional[str]:
    """Given a contract source and a type name used as a state variable
    (e.g. ``LogFile Log``), extract the interface that the attacker's
    helper stub must implement.  Returns a list of function signatures."""
    # Find the contract/interface with this name
    pat = re.compile(
        rf'(?:contract|interface)\s+{re.escape(type_name)}\s*(?:is\s+[^{{]*)?\{{',
        re.S,
    )
    m = pat.search(contract_src)
    if not m:
        return None

    start = m.end()
    depth = 1
    i = start
    while i < len(contract_src) and depth > 0:
        if contract_src[i] == '{':
            depth += 1
        elif contract_src[i] == '}':
            depth -= 1
        i += 1
    body = contract_src[start:i - 1]

    # Extract function signatures
    fns = re.findall(
        r'function\s+(\w+)\s*\(([^)]*)\)\s*([^{;]*)',
        body,
    )
    if not fns:
        return None

    sigs = []
    for fname, params, mods in fns:
        sig = f"function {fname}({params})"
        if 'returns' in mods:
            ret_match = re.search(r'returns\s*\(([^)]*)\)', mods)
            if ret_match:
                sig += f" returns ({ret_match.group(1)})"
        sigs.append(sig)

    return sigs
